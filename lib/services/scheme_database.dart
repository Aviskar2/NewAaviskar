  static List<GovernmentScheme> getByCategory(SchemeCategory category) {
    return schemes.where((s) => s.category == category).toList();
  }

  static List<GovernmentScheme> search(String query) {
    final lower = query.toLowerCase();
    return schemes.where((s) =>
      s.name.toLowerCase().contains(lower) ||
      s.shortName.toLowerCase().contains(lower) ||
      s.description.toLowerCase().contains(lower) ||
      s.category.label.toLowerCase().contains(lower)
    ).toList();
  }

